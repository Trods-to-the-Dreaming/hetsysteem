//-----------------------------------------------------------------------------------------------//
router.get('/enter-world',
	requireLogin,
	showEnterWorld
);
//-----------------------------------------------------------------------------------------------//
router.post('/enter-world',
	requireLogin,
	requireValidation(enterWorldSchema),
	handleEnterWorld
);
