import express from 'express';
//-----------------------------------------------------------------------------------------------//
import { 
	requireLogin
} from '#middleware/auth.js';
import { 
	requireValidation
} from '#middleware/validate.js';
//-----------------------------------------------------------------------------------------------//
import { 
	limitReserveBuildingNameRate,
	requireWorldEntered,
	requireCharacterCreated,
	requireToken
} from './middleware.js';
import {
	enterWorldSchema,
	createCharacterSchema,
	finishTurnSchema,
	checkTurnEditVersionSchema,
	reserveBuildingNameSchema,
	cancelBuildingNameSchema
} from './validation.js';
import {
	showEnterWorld,
	handleEnterWorld,
	showMenu,
	showCharacter,
	showCreateCharacter,
	handleCreateCharacter,
	showStartTurn,
	handleStartTurn,
	showManageBuildings,
	showManageEmploymentContracts,
	showManageRentalAgreements,
	showProduce,
	showTrade,
	showShare,
	showConsume,
	showManageGroup,
	showFinishTurn,
	handleFinishTurn,
	handleCheckTurnEditVersion,
	handleReserveBuildingName,
	handleCancelBuildingName,
	triggerProcessActions,
	showStatistics
} from './controller.js';

